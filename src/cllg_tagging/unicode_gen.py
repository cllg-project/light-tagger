"""Regenerates js/bio-tagger/unicode_py.js: the exact character sets of Python's str.isdigit, str.isupper, re's \\w and \\s,
so the JS tagger tokenises and builds features like the Python one (JS \\p{...} classes differ on e.g. superscript digits, roman-numeral
capitals, U+FEFF). Run from the repo root:  python3 scripts/bio_unicode_gen.py"""
import sys
import unicodedata


def ranges(pred):
    out, a = [], None
    for c in range(0x110000):
        ok = not 0xD800 <= c < 0xE000 and pred(chr(c))
        if ok and a is None:
            a = c
        if not ok and a is not None:
            out.append((a, c - 1))
            a = None
    if a is not None:
        out.append((a, 0x10FFFF))
    return out


def cls(rs):
    return "".join((f"\\u{{{a:x}}}" if a == b else f"\\u{{{a:x}}}-\\u{{{b:x}}}") for a, b in rs)


sets = {"PY_DIGIT": lambda c: c.isdigit(), "PY_UPPER": lambda c: c.isupper(), "PY_WORD": lambda c: c.isalnum() or c == "_",
        "PY_SPACE": lambda c: c.isspace()}
js = (f"// GENERATED by scripts/bio_unicode_gen.py (CPython {sys.version.split()[0]}, unicodedata {unicodedata.unidata_version}); do not edit.\n"
      "// Exact sets behind str.isdigit / str.isupper / re \\w / re \\s.\n")
js += "".join(f"const {k} = /[{cls(ranges(p))}]/u;\n" for k, p in sets.items())
js += "module.exports = { " + ", ".join(sets) + " };\n"
open("js/bio-tagger/unicode_py.js", "w").write(js)
print({k: len(ranges(p)) for k, p in sets.items()}, "ranges;", len(js) // 1024, "KB")
